export function buildMergedVocabularyCatalog(baseCatalog: CatalogWords): CatalogWords {
  const adjectives = [...baseCatalog.adjectives];
  const nouns = [...baseCatalog.nouns];
  const verbs = [...(baseCatalog.verbs || [])];
  const adverbs = [...(baseCatalog.adverbs || [])];

  // Assign default grade tiers to base words if missing
  const assignDefaultTier = (w: Word): Word => {
    if (w.gradeTier) return w;
    const len = w.word.length;
    const tier: GradeTier = len <= 4 ? '1' : len <= 6 ? '2' : len <= 8 ? '3' : '4';
    const meta = getGradeTierMeta(tier);
    return {
      ...w,
      gradeTier: tier,
      powerBonus: w.powerBonus ?? meta.powerBonus,
      morphologyNote:
        w.morphologyNote ||
        `Core ${w.partOfSpeech} of the ${w.element.toUpperCase()} element.`,
    };
  };

  const normAdj = adjectives.map(assignDefaultTier);
  const normNouns = nouns.map(assignDefaultTier);
  const normVerbs = verbs.map(assignDefaultTier);
  const normAdverbs = adverbs.map(assignDefaultTier);

  for (const item of TIERED_VOCAB_WORDS) {
    if (item.partOfSpeech === 'adjective' && !normAdj.some((x) => x.id === item.id)) {
      normAdj.push(item);
    } else if (item.partOfSpeech === 'noun' && !normNouns.some((x) => x.id === item.id)) {
      normNouns.push(item);
    } else if (item.partOfSpeech === 'verb' && !normVerbs.some((x) => x.id === item.id)) {
      normVerbs.push(item);
    } else if (item.partOfSpeech === 'adverb' && !normAdverbs.some((x) => x.id === item.id)) {
      normAdverbs.push(item);
    }
  }

  return {
    adjectives: normAdj,
    nouns: normNouns,
    verbs: normVerbs,
    adverbs: normAdverbs,
  };
}
